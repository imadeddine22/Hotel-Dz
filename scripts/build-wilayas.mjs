// Generates the wilaya + commune data files for frontend and backend from the
// Algeria-wilayas dataset (wilaya-commune.json: [{ code, arabic, ascii, communes: [{ arabic, ascii }] }]).
//
// Usage: node scripts/build-wilayas.mjs <path/to/wilaya-commune.json>
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const src = process.argv[2];
if (!src) {
  console.error('Usage: node scripts/build-wilayas.mjs <wilaya-commune.json>');
  process.exit(1);
}

// French display names (with accents). Listings in the database already use these
// spellings, so they stay the canonical `name`; the dataset's ASCII form is kept alongside.
const FRENCH = {
  1: 'Adrar', 2: 'Chlef', 3: 'Laghouat', 4: 'Oum El Bouaghi', 5: 'Batna', 6: 'Béjaïa',
  7: 'Biskra', 8: 'Béchar', 9: 'Blida', 10: 'Bouira', 11: 'Tamanrasset', 12: 'Tébessa',
  13: 'Tlemcen', 14: 'Tiaret', 15: 'Tizi Ouzou', 16: 'Alger', 17: 'Djelfa', 18: 'Jijel',
  19: 'Sétif', 20: 'Saïda', 21: 'Skikda', 22: 'Sidi Bel Abbès', 23: 'Annaba', 24: 'Guelma',
  25: 'Constantine', 26: 'Médéa', 27: 'Mostaganem', 28: "M'Sila", 29: 'Mascara', 30: 'Ouargla',
  31: 'Oran', 32: 'El Bayadh', 33: 'Illizi', 34: 'Bordj Bou Arréridj', 35: 'Boumerdès',
  36: 'El Tarf', 37: 'Tindouf', 38: 'Tissemsilt', 39: 'El Oued', 40: 'Khenchela',
  41: 'Souk Ahras', 42: 'Tipaza', 43: 'Mila', 44: 'Aïn Defla', 45: 'Naâma',
  46: 'Aïn Témouchent', 47: 'Ghardaïa', 48: 'Relizane', 49: 'Timimoun',
  50: 'Bordj Badji Mokhtar', 51: 'Ouled Djellal', 52: 'Béni Abbès', 53: 'In Salah',
  54: 'In Guezzam', 55: 'Touggourt', 56: 'Djanet', 57: "El M'Ghair", 58: 'El Meniaa',
  59: 'Aflou', 60: 'Barika', 61: 'El Kantara', 62: 'Bir El Ater', 63: 'El Aricha',
  64: 'Ksar Chellala', 65: 'Aïn Oussara', 66: 'Messaad', 67: 'Ksar El Boukhari',
  68: 'Bou Saâda', 69: 'El Abiodh Sidi Cheikh',
};

const data = JSON.parse(fs.readFileSync(src, 'utf8').replace(/^﻿/, ''));
if (!Array.isArray(data)) throw new Error('Expected an array of wilayas');

const wilayas = data
  .map((w) => {
    const code = Number(w.code);
    if (!Number.isInteger(code) || !w.ascii || !w.arabic || !Array.isArray(w.communes)) {
      throw new Error(`Malformed wilaya entry: ${JSON.stringify(w).slice(0, 120)}`);
    }
    return {
      code,
      name: FRENCH[code] || String(w.ascii).trim(),
      arabic: String(w.arabic).trim(),
      ascii: String(w.ascii).trim(),
      communes: w.communes.map((c) => [String(c.ascii).trim(), String(c.arabic).trim()]),
    };
  })
  .sort((a, b) => a.code - b.code);

wilayas.forEach((w, i) => {
  if (w.code !== i + 1) throw new Error(`Wilaya codes must be contiguous from 1; got ${w.code} at position ${i + 1}`);
});

const total = wilayas.reduce((n, w) => n + w.communes.length, 0);
const header = `// AUTO-GENERATED by scripts/build-wilayas.mjs — do not edit by hand.\n// ${wilayas.length} wilayas, ${total} communes.\n`;
const list = wilayas.map(({ code, name, arabic, ascii }) => ({ code, name, arabic, ascii }));
const communes = Object.fromEntries(wilayas.map((w) => [w.code, w.communes]));

const write = (rel, content) => {
  fs.writeFileSync(path.join(root, rel), content);
  console.log(`wrote ${rel}`);
};

// Frontend: list is small and imported everywhere; communes are lazy-loaded JSON.
write(
  'frontend/src/lib/wilayas.js',
  `${header}
/** [{ code, name, arabic, ascii }] ordered by official code. */
export const WILAYA_LIST = ${JSON.stringify(list, null, 2)};

/** French display names, ordered by code — used in select dropdowns. */
export const WILAYAS = WILAYA_LIST.map((w) => w.name);

export const WILAYA_COUNT = WILAYA_LIST.length;

export default WILAYAS;
`
);
write('frontend/src/lib/communes.json', JSON.stringify(communes));

// Backend: seed + validation source.
write(
  'backend/src/utils/wilayas.js',
  `${header}
/** [{ code, name, arabic, ascii }] ordered by official code. */
export const WILAYAS = ${JSON.stringify(list, null, 2)};

/** Array of wilaya names — handy for enum validation. */
export const WILAYA_NAMES = WILAYAS.map((w) => w.name);

export default WILAYAS;
`
);
write('backend/src/utils/communes.json', JSON.stringify(communes));

console.log(`${wilayas.length} wilayas, ${total} communes`);
